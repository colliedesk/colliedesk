package email_test

import (
	"testing"
	"time"

	"github.com/colliedesk/colliedesk/server/internal/email"
)

func systemMail() email.Outgoing {
	return email.Outgoing{FromName: "Colliedesk", FromAddress: "noreply@mail.example.com", ToAddress: "ops@example.net",
		Subject: "Notice", Body: "Something happened.", MessageID: "cd.auto@mail.example.com", Date: time.Now(), Standalone: true}
}

func TestSystemGeneratedMailIsMarkedAutoGenerated(t *testing.T) {
	if got := parseComposed(t, systemMail()).Header.Get("Auto-Submitted"); got != "auto-generated" {
		t.Fatalf("Auto-Submitted=%q, want auto-generated (RFC 3834), so an auto-responder does not answer it", got)
	}
}

func TestAgentRepliesCarryNoAutoSubmittedHeader(t *testing.T) {
	reply := systemMail()
	reply.Standalone = false
	reply.FromAddress, reply.ToAddress = "support@example.com", "customer@example.org"
	if got := parseComposed(t, reply).Header.Get("Auto-Submitted"); got != "" {
		t.Fatalf("a message a person wrote must not claim to be automatic: Auto-Submitted=%q", got)
	}
}

func TestInboundDropsOurOwnSystemMailSoItCannotLoop(t *testing.T) {
	raw, err := email.Compose(systemMail())
	if err != nil {
		t.Fatal(err)
	}
	parsed, err := email.Parse(raw, "")
	if err != nil {
		t.Fatal(err)
	}
	if parsed.DropReason != email.DropAutoSubmitted {
		t.Fatalf("drop reason=%q, want %q", parsed.DropReason, email.DropAutoSubmitted)
	}
}

func TestAnAnswerSentOnItsOwnIsMarkedAutoRepliedAndStaysInTheThread(t *testing.T) {
	reply := systemMail()
	reply.Standalone, reply.AutoReplied = false, true
	reply.Subject, reply.InReplyTo = "Refund", "customer.1@example.org"
	parsed := parseComposed(t, reply)
	if got := parsed.Header.Get("Auto-Submitted"); got != "auto-replied" {
		t.Fatalf("Auto-Submitted=%q, want auto-replied (RFC 3834), so an auto-responder does not answer it", got)
	}
	if got := parsed.Header.Get("Subject"); got != "Re: Refund" {
		t.Errorf("Subject=%q, want the reply's Re: Refund", got)
	}
}
