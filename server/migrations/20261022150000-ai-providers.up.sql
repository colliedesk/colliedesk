-- AI providers and features (#89). A workspace adds its own providers (an Anthropic or
-- OpenAI-compatible endpoint and key) and picks, for each feature ("slot"), the server's provider or
-- one of its own. Every slot starts off: turning one on is an admin's consent to send ticket data to
-- that provider. Every call to a provider leaves one ai_usage row, written before the call. See
-- docs/internals/ai.md.
CREATE TABLE ai_providers (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    workspace_id uuid NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    kind text NOT NULL CHECK (kind IN ('anthropic', 'openai_compatible')),
    label text NOT NULL CHECK (char_length(label) BETWEEN 1 AND 80),
    -- Only an OpenAI-compatible provider has a base URL; Anthropic is always the Claude API.
    base_url text CHECK (char_length(base_url) BETWEEN 1 AND 500),
    auth_kind text NOT NULL CHECK (auth_kind IN ('api_key', 'none')),
    -- The key, sealed (tokenseal, MAILBOX_TOKEN_KEYS) with the context ai-provider:<workspace>:<id>.
    sealed_key bytea,
    sealed_key_id text,
    -- The key's last four characters, the only part ever shown again.
    key_hint text CHECK (char_length(key_hint) BETWEEN 1 AND 4),
    models text[] NOT NULL CHECK (cardinality(models) BETWEEN 1 AND 20),
    -- A provider is saved only after a check passed; a later check can find it failing.
    check_status text NOT NULL CHECK (check_status IN ('ok', 'failing')),
    check_error_code text,
    checked_at timestamptz NOT NULL,
    created_by uuid,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (workspace_id, id),
    UNIQUE (workspace_id, label),
    FOREIGN KEY (workspace_id, created_by) REFERENCES agents(workspace_id, id) ON DELETE SET NULL (created_by),
    CHECK ((sealed_key IS NULL) = (sealed_key_id IS NULL)),
    CHECK ((sealed_key IS NULL) = (key_hint IS NULL)),
    CHECK ((auth_kind = 'api_key') = (sealed_key IS NOT NULL)),
    CHECK ((kind = 'openai_compatible') = (base_url IS NOT NULL)),
    CHECK (kind = 'openai_compatible' OR auth_kind = 'api_key'),
    CHECK ((check_status = 'failing') = (check_error_code IS NOT NULL))
);

-- One row per workspace and feature, created the first time an admin sets it; a missing row is off.
CREATE TABLE ai_slots (
    workspace_id uuid NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    slot text NOT NULL CHECK (slot IN ('triage', 'draft')),
    uses_server boolean NOT NULL DEFAULT false,
    -- No ON DELETE: deleting a provider turns its slots off and records it in the same transaction.
    provider_id uuid,
    model text CHECK (char_length(model) BETWEEN 1 AND 200),
    effort text NOT NULL DEFAULT 'low' CHECK (effort IN ('low', 'medium', 'high')),
    enabled boolean NOT NULL DEFAULT false,
    -- Who agreed that this feature's data goes to its current provider, and when.
    consented_by uuid,
    consented_at timestamptz,
    updated_by uuid,
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (workspace_id, slot),
    FOREIGN KEY (workspace_id, provider_id) REFERENCES ai_providers(workspace_id, id),
    FOREIGN KEY (workspace_id, consented_by) REFERENCES agents(workspace_id, id) ON DELETE SET NULL (consented_by),
    FOREIGN KEY (workspace_id, updated_by) REFERENCES agents(workspace_id, id) ON DELETE SET NULL (updated_by),
    CHECK (NOT (uses_server AND provider_id IS NOT NULL)),
    CHECK (NOT enabled OR ((uses_server OR provider_id IS NOT NULL) AND model IS NOT NULL AND consented_at IS NOT NULL))
);
CREATE INDEX ai_slots_provider ON ai_slots(workspace_id, provider_id) WHERE provider_id IS NOT NULL;

-- Who added, changed or removed a provider or a key, or turned a feature on, off or elsewhere. Never
-- a key: only its last four characters. Labels are copied, so the history outlives the provider.
CREATE TABLE ai_settings_events (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    -- Orders the events of one transaction, which share created_at. Not a key: a restored workspace
    -- brings its values back, and a repeat only affects the order of events of the same instant.
    seq bigint GENERATED BY DEFAULT AS IDENTITY,
    workspace_id uuid NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    kind text NOT NULL CHECK (kind IN ('provider_added', 'provider_changed', 'provider_key_changed', 'provider_removed', 'slot_changed')),
    actor_agent_id uuid,
    -- The agent token's session when a token made the change.
    actor_token_id uuid,
    provider_id uuid,
    provider_label text,
    slot text CHECK (slot IN ('triage', 'draft')),
    detail jsonb NOT NULL DEFAULT '{}',
    created_at timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (workspace_id, actor_agent_id) REFERENCES agents(workspace_id, id) ON DELETE SET NULL (actor_agent_id)
);
CREATE INDEX ai_settings_events_workspace ON ai_settings_events(workspace_id, created_at DESC, seq DESC);

-- One row per call to a provider (each attempt), written as started before the call and finished
-- after it, so a call that times out or a process that dies still leaves its row. No prompt and no
-- answer is ever stored. Provider fields are copied: a deleted provider keeps its history.
CREATE TABLE ai_usage (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    workspace_id uuid NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    feature text NOT NULL CHECK (feature IN ('check', 'triage', 'draft')),
    billed_to text NOT NULL CHECK (billed_to IN ('server', 'workspace_key')),
    provider_id uuid,
    provider_kind text NOT NULL CHECK (provider_kind IN ('anthropic', 'openai_compatible')),
    provider_label text NOT NULL,
    model text NOT NULL,
    status text NOT NULL CHECK (status IN ('started', 'ok', 'error')),
    error_code text,
    stop_reason text CHECK (stop_reason IN ('done', 'max_tokens', 'refused', 'other')),
    -- The model that answered, which a refusal fallback can change.
    served_model text,
    -- NULL when the provider reported no usage: unknown, not zero.
    input_tokens bigint,
    output_tokens bigint,
    cache_read_tokens bigint,
    cache_write_tokens bigint,
    -- One entry per model that ran in this attempt: model, input, output, cache_read, cache_write.
    hops jsonb,
    provider_request_id text,
    actor_agent_id uuid,
    actor_token_id uuid,
    started_at timestamptz NOT NULL,
    finished_at timestamptz,
    latency_ms integer,
    FOREIGN KEY (workspace_id, actor_agent_id) REFERENCES agents(workspace_id, id) ON DELETE SET NULL (actor_agent_id),
    CHECK ((status = 'started') = (finished_at IS NULL)),
    CHECK ((status = 'error') = (error_code IS NOT NULL))
);
CREATE INDEX ai_usage_workspace ON ai_usage(workspace_id, started_at);

DO $$
DECLARE
    app_role text;
    name text;
BEGIN
    SELECT roles[1]::text INTO app_role FROM pg_policies
        WHERE schemaname = current_schema() AND tablename = 'workspaces' AND policyname = 'workspace_isolation';
    IF app_role IS NULL THEN
        RAISE EXCEPTION 'row-level security is not set up in this schema';
    END IF;
    FOREACH name IN ARRAY ARRAY['ai_providers', 'ai_slots', 'ai_settings_events', 'ai_usage'] LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', name);
        EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', name);
        EXECUTE format($policy$CREATE POLICY workspace_isolation ON %1$I FOR ALL TO %2$I
            USING (workspace_id = (SELECT NULLIF(current_setting('app.workspace_id', true), '')::uuid))
            WITH CHECK (workspace_id = (SELECT NULLIF(current_setting('app.workspace_id', true), '')::uuid))$policy$, name, app_role);
        EXECUTE format($policy$CREATE POLICY privileged_access ON %1$I FOR ALL TO %2$I
            USING ((SELECT current_setting('app.privileged', true) = 'on'))
            WITH CHECK ((SELECT current_setting('app.privileged', true) = 'on'))$policy$, name, current_user);
        EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON %I TO %I', name, app_role);
    END LOOP;
END
$$;
