// Strings of the help center's languages and of translations, in the knowledge base chunk.

// languageName names a BCP 47 tag the way the browser does in English (fr → French), or the tag itself.
export function languageName(locale: string): string {
  try {
    const name = new Intl.DisplayNames(['en'], { type: 'language' }).of(locale);
    return name && name !== locale ? `${name} (${locale})` : locale;
  } catch {
    return locale;
  }
}

