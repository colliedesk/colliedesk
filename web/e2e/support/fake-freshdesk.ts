import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync } from 'node:fs';
import { createServer } from 'node:https';
import type { IncomingMessage, ServerResponse } from 'node:http';
import type { Server } from 'node:https';
import type { AddressInfo } from 'node:net';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { ports, scratchDir } from './checkout';

// A local Freshdesk API v2 built from the public API documentation, serving only the documented
// endpoints the importer reads: account, agents, companies, contacts (paged with Link headers),
// tickets (paged, updated_since), a single ticket, archived tickets and their conversations,
// conversations, time entries, search totals, and attachment downloads from a separate file host.
// It answers 429 with Retry-After once, like a real rate limit, and 401 for a wrong API key.
// Knowledge base (solutions): by default the account has an empty one (no categories, no products,
// English only), so the journeys above are unchanged. With knowledgeBase it serves one category
// "Help" holding folder "Start": article 7201 published (with an image on the account host and a
// Spanish translation) and article 7202 a draft.
//
// The fixture is generated by fixed rules so the expected counts can be written down by hand:
//   300 tickets (ids 1-300); ticket 150 is archived (absent from /tickets, served by /tickets/archived/150)
//   120 contacts (ids 1001-1120), 12 inactive (every 10th), contact 1120 has no email
//   conversations per ticket: an incoming customer reply and an agent reply (600),
//     plus a private note on every 5th ticket (60)                          -> 300 + 660 = 960 messages
//   attachments: one on the description of every 10th ticket (30),
//     one on the customer reply of every 30th ticket (10)                   -> 40 attachments
//   time entries: one on every 20th ticket (15); ticket 150 is not a multiple of 20
//   stats (list with include=stats): first response 20 minutes after creation; tickets with id % 4 = 2
//     (resolved) and 3 (closed) resolved at 40 minutes, closed ones closed at 45
//   canned responses: folder 801 "General" holds 2 (ids 9101, 9102), personal folder 802 "My drafts" holds 1 (id 9103)
//   tags: every 3rd ticket "billing"; ticket ids 1, 4, 7, ... "shipping" and "vip"
export const fixture = {
  tickets: 300, archivedTicket: 150, contacts: 120, inactiveContacts: 12, messages: 960, attachments: 40, timeEntries: 15,
  searchableTicket: 42, searchableWord: 'Rotterdam', savedReplies: 2, personalCanned: 1,
  kbArticleCreatedAt: '2023-05-01T09:00:00Z', kbArticleUpdatedAt: '2023-06-01T09:00:00Z',
} as const;

const epoch = Date.UTC(2024, 0, 1, 0, 0, 0);
const iso = (ms: number) => new Date(ms).toISOString().replace('.000Z', 'Z');
export const ticketCreatedAt = (id: number) => iso(epoch + id * 3_600_000);
const topics = ['refund request', 'shipping delay', 'login problem', 'invoice copy'];
export const ticketSubject = (id: number) => id === fixture.searchableTicket ? `Fixture ticket ${id}: parcel stuck in ${fixture.searchableWord}` : `Fixture ticket ${id}: ${topics[id % 4]}`;
// The contact (index from 0) who asked ticket id, and their address; contact 1120 has none.
const requesterIndex = (id: number) => (id - 1) % fixture.contacts;
export const contactEmail = (index: number) => index === fixture.contacts - 1 ? null : `customer${index + 1}@shop${index % 7}.example`;
export const requesterEmail = (id: number) => contactEmail(requesterIndex(id));

interface Options { apiKey: string; agentEmail: string; archiveForbidden?: boolean; cannedUnavailable?: boolean; knowledgeBase?: boolean; fixed?: boolean }

// The main server imports in the app (`collie serve`, built with -tags e2e) from this fake at fixed
// addresses: the server reads them once at start, while the fake starts with its test. The
// certificate is read again by every import, so a new one per test is trusted.
export const inAppFreshdesk = {
  dir: join(scratchDir, 'fake-freshdesk-in-app'),
  env(): Record<string, string> {
    return {
      COLLIEDESK_E2E_FRESHDESK_URL: `https://127.0.0.1:${ports.freshdeskAPI}`, COLLIEDESK_E2E_FRESHDESK_CA: join(this.dir, 'cert.pem'),
      COLLIEDESK_E2E_FRESHDESK_DIAL: `127.0.0.1:${ports.freshdeskAPI},127.0.0.1:${ports.freshdeskFiles}`,
    };
  },
};

export class FakeFreshdesk {
  readonly requests = new Map<string, number>();
  private api?: Server;
  private files?: Server;
  private throttled = false;
  apiURL = '';
  filesURL = '';
  caPath = '';

  constructor(private readonly options: Options) {}

  async start(): Promise<void> {
    const dir = this.options.fixed ? inAppFreshdesk.dir : mkdtempSync(join(tmpdir(), 'colliedesk-fake-freshdesk-'));
    mkdirSync(dir, { recursive: true });
    this.caPath = join(dir, 'cert.pem');
    execFileSync('openssl', ['req', '-x509', '-newkey', 'ec', '-pkeyopt', 'ec_paramgen_curve:prime256v1', '-nodes', '-days', '1',
      '-subj', '/CN=127.0.0.1', '-addext', 'subjectAltName=IP:127.0.0.1', '-keyout', join(dir, 'key.pem'), '-out', this.caPath], { stdio: 'ignore' });
    const tls = { key: readFileSync(join(dir, 'key.pem')), cert: readFileSync(this.caPath) };
    this.api = createServer(tls, (request, response) => this.serveAPI(request, response));
    this.files = createServer(tls, (request, response) => this.serveFile(request, response));
    this.apiURL = await listen(this.api, this.options.fixed ? ports.freshdeskAPI : 0);
    this.filesURL = await listen(this.files, this.options.fixed ? ports.freshdeskFiles : 0);
  }

  // stop also drops open connections: the server's importer keeps them alive, and close() alone waits
  // for them to go idle (about a minute and a half).
  async stop(): Promise<void> {
    await Promise.all([this.api, this.files].map((server) => new Promise((resolve) => {
      server?.close(resolve);
      server?.closeAllConnections();
    })));
  }

  // env is what the e2e importer build reads to reach this fake (cmd/collie/e2e_freshdesk.go).
  env(): Record<string, string> {
    return {
      COLLIEDESK_E2E_FRESHDESK_URL: this.apiURL, COLLIEDESK_E2E_FRESHDESK_CA: this.caPath,
      COLLIEDESK_E2E_FRESHDESK_DIAL: [this.apiURL, this.filesURL].map((url) => new URL(url).host).join(','),
    };
  }

  count(path: string): number { return this.requests.get(path) ?? 0; }

  private serveAPI(request: IncomingMessage, response: ServerResponse) {
    const url = new URL(request.url ?? '/', this.apiURL);
    const path = url.pathname;
    this.requests.set(path, this.count(path) + 1);
    const expected = `Basic ${Buffer.from(`${this.options.apiKey}:X`).toString('base64')}`;
    if (request.headers.authorization !== expected) {
      json(response, 401, { code: 'invalid_credentials', message: 'You have to be logged in to perform this action.' });
      return;
    }
    response.setHeader('X-Ratelimit-Total', '400');
    response.setHeader('X-Ratelimit-Remaining', '399');
    const parts = path.replace(/^\/api\/v2\//, '').split('/');
    const id = Number(parts[parts.length - 1]);
    if (path === '/api/v2/account') {
      json(response, 200, { account_id: 4242, account_name: 'Acme', account_domain: 'acme.freshdesk.com' });
    } else if (path === '/api/v2/agents') {
      this.page(response, url, this.agents());
    } else if (path === '/api/v2/companies') {
      this.page(response, url, [501, 502, 503].map((companyID, index) => ({ id: companyID, name: ['Globex', 'Initech', 'Umbrella'][index], created_at: iso(epoch), updated_at: iso(epoch) })));
    } else if (path === '/api/v2/contacts') {
      if (!this.throttled) {
        this.throttled = true;
        response.setHeader('Retry-After', '1');
        json(response, 429, { message: 'You have exceeded the limit of requests per minute' });
        return;
      }
      this.page(response, url, this.contacts());
    } else if (parts[0] === 'contacts' && parts.length === 2) {
      const contact = this.contacts().find((item) => item.id === id);
      json(response, contact ? 200 : 404, contact ?? { message: 'not found' });
    } else if (path === '/api/v2/canned_response_folders') {
      if (this.options.cannedUnavailable) { json(response, 404, { message: 'not found' }); return; }
      this.page(response, url, [
        { id: 801, name: 'General', personal: false, responses_count: 2, created_at: iso(epoch), updated_at: iso(epoch) },
        { id: 802, name: 'My drafts', personal: true, responses_count: 1, created_at: iso(epoch), updated_at: iso(epoch) },
      ]);
    } else if (parts[0] === 'canned_response_folders' && parts[2] === 'responses') {
      const responses = parts[1] === '801'
        ? [cannedResponse(9101, 801, 'Greeting', 'Hi {{ticket.requester.name}}, thanks for writing.\n{{ticket.agent.name}}'),
          cannedResponse(9102, 801, 'Track your parcel', 'Track it at {{ticket.url}}')]
        : [cannedResponse(9103, 802, 'Private tip', 'Check the carrier log first.')];
      this.page(response, url, responses);
    } else if (path === '/api/v2/search/tickets') {
      json(response, 200, { total: fixture.tickets - 1, results: [] });
    } else if (path === '/api/v2/search/contacts') {
      const active = url.searchParams.get('query') === '"active:true"';
      json(response, 200, { total: active ? fixture.contacts - fixture.inactiveContacts : fixture.inactiveContacts, results: [] });
    } else if (path === '/api/v2/tickets') {
      const since = Date.parse(url.searchParams.get('updated_since') ?? '');
      if (Number.isNaN(since)) { json(response, 400, { message: 'updated_since is required' }); return; }
      const stats = url.searchParams.get('include') === 'stats';
      const listed = this.ticketIDs().filter((ticketID) => ticketID !== fixture.archivedTicket)
        .map((ticketID) => this.ticket(ticketID, false, stats)).filter((ticket) => Date.parse(String(ticket.updated_at)) >= since);
      this.page(response, url, listed);
    } else if (parts[0] === 'tickets' && parts[1] === 'archived' && parts.length === 3) {
      if (this.options.archiveForbidden) { json(response, 403, { code: 'access_denied', message: 'You are not authorized to perform this action.' }); return; }
      json(response, id === fixture.archivedTicket ? 200 : 404, id === fixture.archivedTicket ? this.ticket(id, true) : { message: 'not found' });
    } else if (parts[0] === 'tickets' && parts[1] === 'archived' && parts[3] === 'conversations') {
      const ticketID = Number(parts[2]);
      if (this.options.archiveForbidden) { json(response, 403, { message: 'You are not authorized to perform this action.' }); return; }
      if (ticketID !== fixture.archivedTicket) { json(response, 404, { message: 'not found' }); return; }
      this.page(response, url, this.conversations(ticketID));
    } else if (parts[0] === 'tickets' && parts.length === 2) {
      const exists = id >= 1 && id <= fixture.tickets && id !== fixture.archivedTicket;
      json(response, exists ? 200 : 404, exists ? this.ticket(id, true) : { message: 'not found' });
    } else if (parts[0] === 'tickets' && parts[2] === 'conversations') {
      const ticketID = Number(parts[1]);
      if (ticketID === fixture.archivedTicket || ticketID < 1 || ticketID > fixture.tickets) { json(response, 404, { message: 'not found' }); return; }
      this.page(response, url, this.conversations(ticketID));
    } else if (parts[0] === 'tickets' && parts[2] === 'time_entries') {
      const ticketID = Number(parts[1]);
      this.page(response, url, ticketID % 20 === 0 ? [{
        id: 800_000 + ticketID, billable: true, note: `Call about ticket ${ticketID}`, timer_running: false, agent_id: 101, ticket_id: ticketID,
        time_spent: '00:30', executed_at: ticketCreatedAt(ticketID), start_time: ticketCreatedAt(ticketID),
        created_at: ticketCreatedAt(ticketID), updated_at: ticketCreatedAt(ticketID),
      }] : []);
    } else if (path === '/api/v2/solutions/categories') {
      this.page(response, url, this.options.knowledgeBase ? [{ id: 7001, name: 'Help', description: 'How to use Acme', created_at: iso(epoch), updated_at: iso(epoch) }] : []);
    } else if (path === '/api/v2/solutions/categories/7001/folders' && this.options.knowledgeBase) {
      this.page(response, url, [{ id: 7101, name: 'Start', description: null, parent_folder_id: null, articles_count: 2, sub_folders_count: 0, visibility: 1,
        created_at: iso(epoch), updated_at: iso(epoch) }]);
    } else if (path === '/api/v2/solutions/folders/7101/subfolders' && this.options.knowledgeBase) {
      this.page(response, url, []);
    } else if (path === '/api/v2/solutions/folders/7101/articles' && this.options.knowledgeBase) {
      this.page(response, url, [
        kbArticle(7201, 'Getting started with Acme', 2, `<p>Open <b>Settings</b>.</p><p><img src="${this.apiURL}/helpdesk/attachments/7301" alt="Settings page"></p>`),
        kbArticle(7202, 'Coming soon', 1, '<p>Not ready.</p>'),
      ]);
    } else if (path === '/api/v2/solutions/folders/7101/articles/es' && this.options.knowledgeBase) {
      this.page(response, url, [kbArticle(7201, 'Primeros pasos con Acme', 2, '<p>Abra <b>Ajustes</b>.</p>')]);
    } else if (path === '/api/v2/settings/helpdesk') {
      json(response, 200, { primary_language: 'en', supported_languages: this.options.knowledgeBase ? ['es'] : [], portal_languages: this.options.knowledgeBase ? ['es'] : [] });
    } else if (path === '/api/v2/products') {
      this.page(response, url, []);
    } else if (path === '/helpdesk/attachments/7301' && this.options.knowledgeBase) {
      response.writeHead(200, { 'Content-Type': 'image/png' }).end(kbImage);
    } else {
      json(response, 404, { message: 'not found' });
    }
  }

  private serveFile(request: IncomingMessage, response: ServerResponse) {
    const path = new URL(request.url ?? '/', this.filesURL).pathname;
    this.requests.set(`files:${path}`, this.count(`files:${path}`) + 1);
    const match = path.match(/^\/files\/(\d+)$/);
    if (!match) { response.writeHead(404).end(); return; }
    response.writeHead(200, { 'Content-Type': 'application/octet-stream' }).end(fileBody(Number(match[1])));
  }

  private page(response: ServerResponse, url: URL, items: unknown[]) {
    const perPage = Math.min(Number(url.searchParams.get('per_page') ?? 30) || 30, 100);
    const page = Math.max(Number(url.searchParams.get('page') ?? 1) || 1, 1);
    const slice = items.slice((page - 1) * perPage, page * perPage);
    if (page * perPage < items.length) {
      const next = new URL(url);
      next.searchParams.set('page', String(page + 1));
      response.setHeader('Link', `<${next.toString()}>; rel="next"`);
    }
    json(response, 200, slice);
  }

  private agents() {
    return [
      { id: 101, available: true, occasional: false, type: 'support_agent', contact: { active: true, email: this.options.agentEmail, name: 'Alice Agent' }, created_at: iso(epoch), updated_at: iso(epoch) },
      { id: 102, available: false, occasional: true, type: 'support_agent', contact: { active: false, email: 'bob@former.example', name: 'Bob Former' }, created_at: iso(epoch), updated_at: iso(epoch) },
    ];
  }

  private contacts() {
    return Array.from({ length: fixture.contacts }, (_, index) => {
      const id = 1001 + index;
      return {
        id, name: `Customer ${index + 1}`, email: contactEmail(index),
        phone: id === 1120 ? '+1 555 0100' : null, mobile: null, company_id: [501, 502, null][index % 3], active: index % 10 !== 9,
        other_emails: [], created_at: iso(epoch - 86_400_000 + index * 60_000), updated_at: iso(epoch - 86_400_000 + index * 60_000),
      };
    });
  }

  private ticketIDs() { return Array.from({ length: fixture.tickets }, (_, index) => index + 1); }

  private ticket(id: number, full: boolean, stats = false) {
    const created = epoch + id * 3_600_000;
    const subject = ticketSubject(id);
    const ticket: Record<string, unknown> = {
      id, subject, status: [2, 3, 4, 5][id % 4], priority: [1, 2, 3, 4][id % 4], source: 1, type: id % 2 ? 'Question' : 'Problem',
      spam: false, deleted: false, requester_id: 1001 + requesterIndex(id), responder_id: id % 4 === 0 ? 101 : null,
      company_id: null, group_id: null, tags: [...(id % 3 === 0 ? ['billing'] : []), ...(id % 3 === 1 ? ['shipping', 'vip'] : [])],
      due_by: null, fr_due_by: null, cc_emails: [], fwd_emails: [], to_emails: null,
      created_at: iso(created), updated_at: iso(created + 30 * 60_000),
    };
    if (stats) {
      // Resolved (4) and closed (5) tickets were resolved 40 minutes after they were created, closed ones closed at 45.
      const status = [2, 3, 4, 5][id % 4];
      ticket.stats = {
        first_responded_at: iso(created + 20 * 60_000),
        resolved_at: status >= 4 ? iso(created + 40 * 60_000) : null,
        closed_at: status === 5 ? iso(created + 45 * 60_000) : null,
      };
    }
    if (full) {
      ticket.description = `<div>Description of ticket ${id}.</div>`;
      ticket.description_text = `Description of ticket ${id}.`;
      ticket.attachments = id % 10 === 0 ? [this.attachment(900_000 + id, `invoice-${id}.pdf`, created)] : [];
    }
    return ticket;
  }

  private conversations(id: number) {
    const created = epoch + id * 3_600_000;
    const customer = this.contacts()[(id - 1) % fixture.contacts];
    const items: unknown[] = [
      { id: 100_000 + id * 10 + 1, body: `<div>Customer follow-up on ${id}</div>`, body_text: `Customer follow-up on ${id}`, incoming: true, private: false,
        user_id: customer.id, support_email: null, source: 0, ticket_id: id, from_email: customer.email, to_emails: ['support@acme.example'],
        cc_emails: [], bcc_emails: [], attachments: id % 30 === 0 ? [this.attachment(910_000 + id, `photo-${id}.png`, created + 600_000)] : [],
        created_at: iso(created + 10 * 60_000), updated_at: iso(created + 10 * 60_000) },
      { id: 100_000 + id * 10 + 2, body: `<div>Agent answer on ${id}</div>`, body_text: `Agent answer on ${id}`, incoming: false, private: false,
        user_id: 101, support_email: 'support@acme.example', source: 0, ticket_id: id, from_email: null, to_emails: [customer.email].filter(Boolean),
        cc_emails: [], bcc_emails: [], attachments: [], created_at: iso(created + 20 * 60_000), updated_at: iso(created + 20 * 60_000) },
    ];
    if (id % 5 === 0) {
      items.push({ id: 100_000 + id * 10 + 3, body: `<div>Internal note on ${id}</div>`, body_text: `Internal note on ${id}`, incoming: false, private: true,
        user_id: 102, support_email: null, source: 2, ticket_id: id, from_email: null, to_emails: [], cc_emails: [], bcc_emails: [], attachments: [],
        created_at: iso(created + 25 * 60_000), updated_at: iso(created + 25 * 60_000) });
    }
    return items;
  }

  private attachment(id: number, name: string, created: number) {
    return { id, name, content_type: name.endsWith('.pdf') ? 'application/pdf' : 'image/png', size: fileBody(id).length,
      attachment_url: `${this.filesURL}/files/${id}`, created_at: iso(created), updated_at: iso(created) };
  }
}

export function fileBody(id: number): Buffer {
  return Buffer.from(`attachment ${id} bytes from the fake Freshdesk file host`);
}

// kbImage is a PNG: the signature, then bytes the test can recognise.
export const kbImage = Buffer.concat([Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]), Buffer.from('knowledge base image')]);

function kbArticle(id: number, title: string, status: number, description: string) {
  return { id, type: 1, category_id: 7001, folder_id: 7101, agent_id: 101, title, status, description, description_text: '', tags: ['start'],
    seo_data: {}, hits: 3, thumbs_up: 1, thumbs_down: 0, created_at: fixture.kbArticleCreatedAt, updated_at: fixture.kbArticleUpdatedAt };
}

function cannedResponse(id: number, folder: number, title: string, content: string) {
  return { id, title, folder_id: folder, content, content_html: `<div>${content.replace(/\n/g, '<br>')}</div>`, attachments: [], created_at: iso(epoch), updated_at: iso(epoch) };
}

function json(response: ServerResponse, status: number, value: unknown) {
  response.writeHead(status, { 'Content-Type': 'application/json' }).end(JSON.stringify(value));
}

async function listen(server: Server, port: number): Promise<string> {
  await new Promise<void>((resolve) => server.listen(port, '127.0.0.1', resolve));
  return `https://127.0.0.1:${(server.address() as AddressInfo).port}`;
}
